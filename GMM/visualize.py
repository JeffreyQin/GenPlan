import matplotlib.pyplot as plt
import numpy as np

def visualize_binary_array(arr):
    """
    Visualize a 2D array of 0s and 1s.
    0 -> white
    1 -> black
    """
    arr = np.array(arr)

    plt.figure(figsize=(6, 6))
    plt.imshow(arr, cmap='gray', interpolation='nearest')
    plt.title("2D Binary Array Visualization")
    plt.colorbar(label="Value")
    plt.show()


